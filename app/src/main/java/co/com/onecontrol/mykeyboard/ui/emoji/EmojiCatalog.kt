        for (item in all) {
            if (item.char == q || item.tags.any { it.contains(q) || q.contains(it) }) {
                results.add(item.char)
            }
        }
        return results.distinct()
    }

    fun searchGifs(query: String): List<GifItem> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return GIF_ITEMS
        return GIF_ITEMS.filter { gif ->
            gif.title.lowercase().contains(q) ||
            gif.tags.any { it.contains(q) || q.contains(it) }
        }
    }
